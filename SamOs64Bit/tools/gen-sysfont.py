#!/usr/bin/env python3
"""Generate SamOS's 8x16 system font from a public-domain source.

Source: assets/fonts/font8x8_basic.h (Daniel Hepper's font8x8, which
is Marcel Sondaar's public-domain 8x8 font; see the header). Each
8x8 glyph is doubled vertically to fill an 8x16 cell.

Outputs (both checked in, regenerate with `python3 tools/gen-sysfont.py`
from SamOs64Bit/):
  assets/sysfont.bmp          24-bit BMP font sheet the kernel loads
                              from @:/sysfont.bmp (16 x 6 cells of
                              8x16, ASCII 32..127, white on black).
  src/graphics/font_builtin.c the same glyphs compiled into the
                              kernel, used when the BMP is missing.

No third-party Python modules needed.
"""
import os
import re
import struct
import sys

CELL_W, CELL_H = 8, 16
FIRST, LAST = 32, 127            # inclusive
COLS = 16
COUNT = LAST - FIRST + 1         # 96
ROWS = (COUNT + COLS - 1) // COLS

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)


def load_font8x8(path):
    text = open(path, encoding="utf-8").read()
    body = text[text.index("font8x8_basic"):]
    rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}", body)
    glyphs = [[int(b, 16) for b in r.split(",")] for r in rows]
    if len(glyphs) != 128:
        sys.exit(f"expected 128 glyphs in {path}, found {len(glyphs)}")
    return glyphs


def to_8x16(glyph8):
    # Each source row becomes two rows. Bit 0 is the leftmost pixel,
    # which is also the kernel's packing order for 8-wide glyphs.
    out = []
    for row in glyph8:
        out += [row, row]
    return out


def write_bmp(path, glyphs16):
    width, height = COLS * CELL_W, ROWS * CELL_H
    pix = [[0] * width for _ in range(height)]
    for i, g in enumerate(glyphs16):
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        for y in range(CELL_H):
            for x in range(CELL_W):
                if (g[y] >> x) & 1:
                    pix[cy + y][cx + x] = 1
    row_bytes = width * 3
    pad = (4 - row_bytes % 4) % 4
    data = bytearray()
    for y in range(height - 1, -1, -1):          # bottom-up
        for x in range(width):
            v = 0xFF if pix[y][x] else 0x00
            data += bytes((v, v, v))
        data += b"\x00" * pad
    header = struct.pack("<2sIHHI", b"BM", 54 + len(data), 0, 0, 54)
    info = struct.pack("<IiiHHIIiiII", 40, width, height, 1, 24, 0,
                       len(data), 2835, 2835, 0, 0)
    with open(path, "wb") as f:
        f.write(header + info + data)


def write_c(path, glyphs16):
    lines = [
        "// GENERATED by tools/gen-sysfont.py - do not edit by hand.",
        "//",
        "// 8x16 glyphs for ASCII 32..127, doubled vertically from the",
        "// public-domain font8x8 (Daniel Hepper / Marcel Sondaar). One",
        "// byte per row, bit 0 = leftmost pixel. Compiled in so the",
        "// terminal still has a font when @:/sysfont.bmp is missing.",
        "",
        "#include \"graphics/font_builtin.h\"",
        "",
        f"const uint8_t font_builtin_8x16_data[FONT_BUILTIN_CHARACTER_COUNT * FONT_BUILTIN_HEIGHT] = {{",
    ]
    for i, g in enumerate(glyphs16):
        ch = chr(FIRST + i)
        label = repr(ch) if 32 <= ord(ch) < 127 else f"0x{ord(ch):02X}"
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in g) + f",  // {label}")
    lines.append("};")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    glyphs = load_font8x8(os.path.join(root, "assets", "fonts", "font8x8_basic.h"))
    glyphs16 = [to_8x16(glyphs[c]) for c in range(FIRST, LAST + 1)]
    write_bmp(os.path.join(root, "assets", "sysfont.bmp"), glyphs16)
    write_c(os.path.join(root, "src", "graphics", "font_builtin.c"), glyphs16)
    print(f"wrote assets/sysfont.bmp ({COLS * CELL_W}x{ROWS * CELL_H}) and src/graphics/font_builtin.c")


if __name__ == "__main__":
    main()
